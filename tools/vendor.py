#!/usr/bin/env python3
"""
Fetch the third-party libraries the pages use into vendor/, at pinned versions.

The dashboard has no build step and no npm dependencies; libraries are
committed under vendor/<name>-<version>/ and loaded same-origin. This script is
how they get there (and how they get updated): bump a version in LIBRARIES,
run `make vendor`, update the <script>/<link> paths, commit.

For each library it downloads the exact version's tarball from the npm
registry, verifies it against the registry's integrity hash (sha512), extracts
only the files the pages load plus the license, and regenerates
vendor/SHA256SUMS and vendor/README.md. `make vendor-check` verifies the
committed files against SHA256SUMS offline.

Usage: tools/vendor.py            # fetch / refresh everything in LIBRARIES
"""

import base64
import hashlib
import io
import json
import os
import shutil
import sys
import tarfile
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VENDOR = os.path.join(ROOT, "vendor")
REGISTRY = "https://registry.npmjs.org"

# name, version, files to copy (path inside the npm package), license file.
LIBRARIES = [
    {
        "name": "tablesort", "version": "5.7.0",
        "files": ["dist/tablesort.min.js", "dist/sorts/tablesort.number.min.js",
                  "tablesort.css"],
        "used_by": "sortable tables (builder, ews-queue, gardening, index, queue, worker)",
    },
    {
        "name": "chart.js", "version": "4.6.1",
        "files": ["dist/chart.umd.min.js"],
        "used_by": "charts (job-duration, results-stats)",
    },
    {
        "name": "chartjs-adapter-date-fns", "version": "3.0.0",
        "files": ["dist/chartjs-adapter-date-fns.bundle.min.js"],
        "used_by": "time axis for Chart.js (job-duration)",
    },
]
LICENSE_NAMES = ("LICENSE", "LICENSE.md", "LICENSE.txt", "LICENCE", "license")


def fetch(url):
    req = urllib.request.Request(url, headers={"User-Agent": "webkit-bots-dashboard vendor.py"})
    with urllib.request.urlopen(req, timeout=60) as resp:
        return resp.read()


def check_integrity(data, integrity):
    algo, _, expected = integrity.partition("-")
    digest = base64.b64encode(hashlib.new(algo, data).digest()).decode()
    if digest != expected:
        sys.exit("integrity mismatch for tarball (%s)" % integrity)


def vendor_library(lib):
    name, version = lib["name"], lib["version"]
    meta = json.loads(fetch("%s/%s/%s" % (REGISTRY, name, version)))
    tarball = fetch(meta["dist"]["tarball"])
    check_integrity(tarball, meta["dist"]["integrity"])

    dest = os.path.join(VENDOR, "%s-%s" % (name, version))
    shutil.rmtree(dest, ignore_errors=True)
    os.makedirs(dest)
    with tarfile.open(fileobj=io.BytesIO(tarball)) as tar:
        members = {m.name.split("/", 1)[1]: m for m in tar.getmembers() if "/" in m.name}
        license_file = next((n for n in LICENSE_NAMES if n in members), None)
        if not license_file:
            sys.exit("%s@%s: no license file found" % (name, version))
        for path in lib["files"] + [license_file]:
            data = tar.extractfile(members[path]).read()
            out = os.path.join(dest, os.path.basename(path))
            with open(out, "wb") as f:
                f.write(data)
    return {"license": meta.get("license", "?"), "dir": os.path.basename(dest)}


def write_manifests(results):
    sums = []
    for dirpath, _, files in sorted(os.walk(VENDOR)):
        for fn in sorted(files):
            path = os.path.join(dirpath, fn)
            rel = os.path.relpath(path, VENDOR)
            if rel in ("README.md", "SHA256SUMS"):
                continue
            with open(path, "rb") as f:
                sums.append("%s  %s" % (hashlib.sha256(f.read()).hexdigest(), rel))
    with open(os.path.join(VENDOR, "SHA256SUMS"), "w") as f:
        f.write("\n".join(sums) + "\n")

    lines = [
        "# Vendored third-party libraries",
        "",
        "Generated by `tools/vendor.py` (`make vendor`); don't edit files here by hand.",
        "To update a library, bump its version in `tools/vendor.py`, run `make vendor`,",
        "update the `<script>` / `<link>` paths in the pages, and commit.",
        "`make vendor-check` verifies these files against `SHA256SUMS`.",
        "",
        "| Library | Version | License | Directory | Used by |",
        "|---|---|---|---|---|",
    ]
    for lib, res in zip(LIBRARIES, results):
        lines.append("| [%s](https://www.npmjs.com/package/%s) | %s | %s | `%s/` | %s |"
                     % (lib["name"], lib["name"], lib["version"], res["license"],
                        res["dir"], lib["used_by"]))
    with open(os.path.join(VENDOR, "README.md"), "w") as f:
        f.write("\n".join(lines) + "\n")


def main():
    os.makedirs(VENDOR, exist_ok=True)
    results = []
    for lib in LIBRARIES:
        print("vendoring %s@%s" % (lib["name"], lib["version"]))
        results.append(vendor_library(lib))
    # Drop directories of versions no longer listed.
    wanted = {r["dir"] for r in results}
    for entry in os.listdir(VENDOR):
        if os.path.isdir(os.path.join(VENDOR, entry)) and entry not in wanted:
            print("removing stale %s" % entry)
            shutil.rmtree(os.path.join(VENDOR, entry))
    write_manifests(results)


if __name__ == "__main__":
    main()
